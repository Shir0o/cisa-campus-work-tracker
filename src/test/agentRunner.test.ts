import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {
  applyAssetOptimization,
  generatePrSummary,
  type AppliedImprovement,
} from '../../scripts/agent/runner';

describe('agent runner', () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'runner-test-'));
  });

  afterEach(() => {
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  describe('applyAssetOptimization', () => {
    it('optimizes SVG in place and returns savings', () => {
      const svgPath = path.join(tempDir, 'test.svg');
      const unoptimized = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 50 50">
  <circle cx="25" cy="25" r="20" fill="#00ff00" />
</svg>`;
      fs.writeFileSync(svgPath, unoptimized, 'utf8');

      const result = applyAssetOptimization(svgPath);
      expect(result.success).toBe(true);
      expect(result.bytesSaved).toBeGreaterThan(0);

      const modified = fs.readFileSync(svgPath, 'utf8');
      expect(modified.length).toBeLessThan(unoptimized.length);
      expect(modified.includes('viewBox="0 0 50 50"')).toBe(true);
    });

    it('handles non-existent file gracefully', () => {
      const result = applyAssetOptimization(path.join(tempDir, 'missing.svg'));
      expect(result.success).toBe(false);
      expect(result.bytesSaved).toBe(0);
    });
  });

  describe('generatePrSummary', () => {
    it('generates structured Markdown PR body with badge and table', () => {
      const applied: AppliedImprovement[] = [
        {
          id: 'asset-svg-google',
          category: 'asset-optimization',
          title: 'Optimize public/google.svg',
          canAutoMerge: true,
          details: 'Saved 42 B via lossless SVGO',
        },
      ];

      const summary = generatePrSummary(applied, true);
      expect(summary).toContain('## 🛠️ Weekly Automated Micro-Improvements');
      expect(summary).toContain('Optimize public/google.svg');
      expect(summary).toContain('Auto-Merge');
      expect(summary).toContain('Passed (`npm run typecheck && npm run lint && npm run test:coverage && npm run build`)');
    });

    it('marks review required when non-automergeable items exist', () => {
      const applied: AppliedImprovement[] = [
        {
          id: 'token-fix',
          category: 'design-token-drift',
          title: 'Migrate hardcoded colors',
          canAutoMerge: false,
          details: 'Migrated 3 hex codes to var(--border)',
        },
      ];

      const summary = generatePrSummary(applied, false);
      expect(summary).toContain('Requires Human Review');
    });
  });
});
