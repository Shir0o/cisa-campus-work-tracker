export function reporterLabelColor(label: string): string {
  let hash = 0;
  for (let index = 0; index < label.length; index += 1) {
    hash = (hash * 31 + label.charCodeAt(index)) >>> 0;
  }
  return REPORTER_LABEL_COLORS[hash % REPORTER_LABEL_COLORS.length];
}

export function isOpaqueRecordId(token: string): boolean {
  return /^[A-Za-z0-9_-]{16,}$/.test(token) && /[a-z]/.test(token) && /[A-Z]/.test(token);
}

export function redactRecordIds(url: string): string {
  if (typeof url !== 'string' || url === '') return url;
  return url.replace(/[A-Za-z0-9_-]+/g, (token) => (isOpaqueRecordId(token) ? ':id' : token));
}

export function shouldDropComment(raw: string | null | undefined): boolean {
  const body = (raw || '').trim();
  if (!body) return true;
  return body.toLowerCase().includes(TRIAGE_COMMENT_MARKER);
}

export function replyPrefix(authorRole: 'submitter' | 'team', authorName?: string): string {
  return authorRole === 'submitter'
    ? '**Reporter replied:**'
    : `**${authorName || 'The team'} replied from the app:**`;
}

export function parseIssueUrl(issueUrl: string): { owner: string; repo: string; issueNumber: string } | null {
  let parsed: URL;
  try {
    parsed = new URL(issueUrl);
  } catch {
    return null;
  }
  if (parsed.protocol !== 'https:') return null;
  if (parsed.hostname !== 'github.com' && parsed.hostname !== 'www.github.com') return null;

  const match = parsed.pathname.match(/^\/([A-Za-z0-9._-]+)\/([A-Za-z0-9._-]+)\/issues\/(\d+)$/);
  if (!match) return null;
  if (match[1] === '.' || match[1] === '..' || match[2] === '.' || match[2] === '..') return null;
  return { owner: match[1], repo: match[2], issueNumber: match[3] };
}

export function parsePullApiUrl(candidate: string): { owner: string; repo: string; pullNumber: string } | null {
  let parsed: URL;
  try {
    parsed = new URL(candidate);
  } catch {
    return null;
  }
  if (parsed.protocol !== 'https:' || parsed.hostname !== 'api.github.com') return null;

  const match = parsed.pathname.match(/^\/repos\/([A-Za-z0-9._-]+)\/([A-Za-z0-9._-]+)\/pulls\/(\d+)$/);
  if (!match) return null;
  return { owner: match[1], repo: match[2], pullNumber: match[3] };
}

