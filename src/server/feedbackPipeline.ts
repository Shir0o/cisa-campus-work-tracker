const GITHUB_SAFE_SEGMENT = /^[A-Za-z0-9._-]+$/;

function githubHeaders(token: string) {
  return {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'Content-Type': 'application/json',
    'User-Agent': 'CISA-Campus-Work-Tracker-Server',
  };
}

async function githubApiFetch(
  segments: string[],
  init: RequestInit,
  search: '' | '?per_page=100' = '',
): Promise<Response | null> {
  if (segments.length === 0 || !segments.every((seg) => GITHUB_SAFE_SEGMENT.test(seg))) {
    console.warn('Refusing a GitHub API request with an unexpected path segment.');
    return null;
  }
  const path = segments.map((seg) => encodeURIComponent(seg)).join('/');
  return fetch(`https://api.github.com/${path}${search}`, init);
}

export async function ensureGitHubLabel(
  repo: string,
  token: string,
  label: string,
  fetchImpl: typeof fetch = fetch,
): Promise<boolean> {
  const response = await fetchImpl(`https://api.github.com/repos/${repo}/labels`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'Content-Type': 'application/json',
      'User-Agent': 'CISA-Campus-Work-Tracker-Server',
    },
    body: JSON.stringify({
      name: label,
      color: reporterLabelColor(label),
    }),
  });

  if (response.ok) return true;
  if (response.status === 422) {
    const text = await response.text();
    return text.includes('already_exists');
  }
  return false;
}

export class DefaultGitHubFeedbackPort implements GitHubFeedbackPort {
  private repo: string;
  constructor(repo: string) {
    this.repo = repo;
  }
  private get githubRepo(): string {
    return process.env.GITHUB_REPO || this.repo || process.env.VITE_GITHUB_REPO || 'Shir0o/cisa-campus-work-tracker';
  }
  private get token() {
    return process.env.GITHUB_TOKEN;
  }

  async createIssue(params: { title: string; body: string; labels: string[] }): Promise<{ html_url: string; number: number } | null> {
    const token = this.token;
    const repo = this.githubRepo;
    if (!token || !repo) {
      console.warn("GitHub credentials not fully configured; skipping auto GitHub issue creation.");
      return null;
    }
    try {
      const res = await fetch(`https://api.github.com/repos/${repo}/issues`, {
        method: 'POST',
        headers: githubHeaders(token),
        body: JSON.stringify(params),
      });
      if (!res.ok) {
        const errorText = await res.text();
        console.error("GitHub API error creating issue: " + res.status + " - " + errorText);
        return null;
      }
      const data = await res.json();
      if (data?.html_url) {
        console.log('Auto-created GitHub issue: ' + data.html_url);
      }
      return data;
    } catch (err) {
      console.error("Failed to auto-create GitHub issue:", err);
      return null;
    }
  }

  async ensureLabel(name: string): Promise<boolean> {
    const token = this.token;
    const repo = this.githubRepo;
    if (!token || !repo) return false;
    return ensureGitHubLabel(repo, token, name);
  }

  async updateIssueState(issueUrl: string, state: 'open' | 'closed', reason?: 'completed' | 'not_planned'): Promise<boolean> {
    if (!issueUrl) return false;
    const token = this.token;
    if (!token) {
      console.warn("GITHUB_TOKEN not configured; skipping GitHub issue status sync.");
      return false;
    }
    const parsed = parseIssueUrl(issueUrl);
    if (!parsed) {
      console.error("Invalid GitHub issue URL format for sync: %s", issueUrl);
      return false;
    }
    const { owner, repo, issueNumber } = parsed;
    try {
      const payload: any = { state };
      if (state === 'closed' && reason) {
        payload.state_reason = reason;
      }
      const res = await githubApiFetch(['repos', owner, repo, 'issues', issueNumber], {
        method: 'PATCH',
        headers: githubHeaders(token),
        body: JSON.stringify(payload),
      });
      if (!res) return false;
      if (!res.ok) {
        console.error("GitHub API error updating issue: %s - %s", res.status, await res.text());
        return false;
      }
      console.log("Successfully updated GitHub issue state to %s (%s) for %s", state, reason || 'no reason', issueUrl);
      return true;
    } catch (error) {
      console.error("Failed to update GitHub issue state for %s: %o", issueUrl, error);
      return false;
    }
  }

  async postComment(issueUrl: string, body: string): Promise<number | null> {
    const token = this.token;
    if (!token || !issueUrl) return null;
    const parsed = parseIssueUrl(issueUrl);
    if (!parsed) return null;
    const { owner, repo, issueNumber } = parsed;
    try {
      const res = await githubApiFetch(['repos', owner, repo, 'issues', issueNumber, 'comments'], {
        method: 'POST',
        headers: githubHeaders(token),
        body: JSON.stringify({ body }),
      });
      if (!res) return null;
      if (!res.ok) {
        console.error("GitHub API error posting comment: %s - %s", res.status, await res.text());
        return null;
      }
      const data = await res.json();
      return typeof data?.id === 'number' ? data.id : null;
    } catch (error) {
      console.error(`Failed to post a comment to ${issueUrl}:`, error);
      return null;
    }
  }

  async editComment(issueUrl: string, commentId: number, body: string): Promise<boolean> {
    const token = this.token;
    if (!token || !issueUrl) return false;
    const parsed = parseIssueUrl(issueUrl);
    if (!parsed) return false;
    const { owner, repo } = parsed;
    try {
      const res = await githubApiFetch(['repos', owner, repo, 'issues', 'comments', String(commentId)], {
        method: 'PATCH',
        headers: githubHeaders(token),
        body: JSON.stringify({ body }),
      });
      if (!res) return false;
      if (!res.ok) {
        console.error("GitHub API error editing comment: %s - %s", res.status, await res.text());
        return false;
      }
      return true;
    } catch (error) {
      console.error(`Failed to edit a comment on ${issueUrl}:`, error);
      return false;
    }
  }

  async fetchIssueTimeline(issueUrl: string): Promise<any[] | null> {
    const token = this.token;
    if (!token) return null;
    const parsed = parseIssueUrl(issueUrl);
    if (!parsed) return null;
    const { owner, repo, issueNumber } = parsed;
    const res = await githubApiFetch(
      ['repos', owner, repo, 'issues', issueNumber, 'timeline'],
      { headers: githubHeaders(token) },
      '?per_page=100',
    );
    if (!res || !res.ok) {
      console.warn("Feedback close summary: timeline fetch failed with status %s.", res?.status ?? "refused");
      return null;
    }
    return res.json();
  }

  async fetchPullRequest(pullApiUrl: string): Promise<{ title: string; body: string } | null> {
    const token = this.token;
    if (!token) return null;
    const parsed = parsePullApiUrl(pullApiUrl);
    if (!parsed) {
      console.warn("Feedback close summary: the linked PR URL was not a GitHub API pull URL.");
      return null;
    }
    const res = await githubApiFetch(
      ['repos', parsed.owner, parsed.repo, 'pulls', parsed.pullNumber],
      { headers: githubHeaders(token) },
    );
    if (!res || !res.ok) {
      console.warn("Feedback close summary: PR fetch failed with status %s.", res?.status ?? "refused");
      return null;
    }
    return res.json();
  }
}

let cachedAiClient: GoogleGenAI | null = null;
function getAiClient(): GoogleGenAI {
  if (!cachedAiClient) {
    cachedAiClient = new GoogleGenAI({});
  }
  return cachedAiClient;
}

export class DefaultFeedbackAIPort implements FeedbackAIPort {
  async launderComment(raw: string): Promise<string | null> {
    try {
      const response = await getAiClient().models.generateContent({
        model: 'gemini-3.5-flash',
        contents: raw,
        config: {
          systemInstruction: LAUNDER_INSTRUCTION,
          responseMimeType: 'application/json',
          responseSchema: {
            type: Type.OBJECT,
            properties: {
              relay: { type: Type.BOOLEAN, description: 'Whether this comment has anything worth telling the reporter.' },
              text: { type: Type.STRING, description: 'The restated comment, at most two sentences. Empty when relay is false.' },
            },
            required: ['relay', 'text'],
          },
        },
      });

      const parsed = JSON.parse(response.text || '{}');
      if (!parsed.relay) return null;
      const text = (parsed.text || '').trim();
      return text || null;
    } catch (error) {
      console.error("Failed to launder issue comment; dropping it:", error);
      return null;
    }
  }

  async summarizePRClose(title: string, body: string): Promise<string | null> {
    try {
      const response = await getAiClient().models.generateContent({
        model: 'gemini-3.5-flash',
        contents: `Pull request title: ${title || ''}\n\nPull request description:\n${(body || '').slice(0, 8000)}`,
        config: {
          systemInstruction: CLOSE_SUMMARY_INSTRUCTION,
          responseMimeType: 'application/json',
          responseSchema: {
            type: Type.OBJECT,
            properties: {
              usable: { type: Type.BOOLEAN, description: 'Whether the PR describes a change the reporter would notice.' },
              text: { type: Type.STRING, description: 'One or two sentences for the reporter. Empty when usable is false.' },
            },
            required: ['usable', 'text'],
          },
        },
      });

      const summary = JSON.parse(response.text || '{}');
      if (!summary.usable) return null;
      const text = (summary.text || '').trim();
      return text || null;
    } catch (error) {
      console.error("Failed to build a close summary from the linked PR:", error);
      return null;
    }
  }
}

/**
 * The `replyCount` to write on a Note when a Follow-up lands on it.
 *
 * A Note written before the field existed has no count, and incrementing from
 * zero would report its newest Follow-up as the whole thread. So the first
 * write counts what the thread already holds — once — and every write after
 * that increments. Nothing is backfilled: a Note that never gets another
 * Follow-up keeps saying "not known" rather than guessing.
 */
async function nextReplyCount(
  note: Record<string, any>,
  replies: { get(): Promise<{ size: number }> },
): Promise<number | ReturnType<typeof FieldValue.increment>> {
  if (typeof note.replyCount === 'number' && typeof FieldValue?.increment === 'function') {
    return FieldValue.increment(1);
  }
  const existing = await replies.get();
  return existing.size + 1;
}

